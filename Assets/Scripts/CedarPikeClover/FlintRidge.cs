using UnityEngine;

// Every number the game lays out with, in the canvas reference space the template
// defines (CanvasScaler 1242 x 2688). Nothing is measured by eye and nothing is
// duplicated: the HUD, the trail, the scenario taps and the generator all read here.
public static class InjuryComposeMech
{
    public static float TogetherStrife { get; } = 2688f;
    public static float ResistanceRich { get; } = 1242f;
    public static float ExpertSpike { get; } = 1900f;
    public static float SurroundMayorDigest { get; } = 190f;

    public static float ProceedEdgeObserve
    {
        get
        {
            OtherCeiling.FillUnlitPlanet = OtherCeiling.HazeHaze(OtherCeiling.FillUnlitPlanet, 119);
            OtherCeiling.FillUnlitPlanet = OtherCeiling.WillowJade(OtherCeiling.FillUnlitPlanet, 143);
            OtherCeiling.FillUnlitPlanet = OtherCeiling.HazeHaze(OtherCeiling.FillUnlitPlanet, 234);
            return ExpertSpike - IncludeTongue;
        }
    }

    // Panel-space centre of a HUD element -> local position inside a stretched layer.
    public static Vector2 FromPanel(float DecadeTrueshot, float GasNeckTomato)
    {
        OtherCeiling.FillUnlitPlanet = OtherCeiling.OakCliff(OtherCeiling.FillUnlitPlanet, 38);
        OtherCeiling.FillUnlitPlanet = OtherCeiling.GroveDune(OtherCeiling.FillUnlitPlanet, 164);
        OtherCeiling.FillUnlitPlanet = OtherCeiling.HazeHaze(OtherCeiling.FillUnlitPlanet, 198);
        return new Vector2(DecadeTrueshot - ResistanceRich * 0.5f, GasNeckTomato - TogetherStrife * 0.5f);
    }

    public static float FullServeBattery
    {
        get
        {
            int HorizontalBasicSampler = 32144;
            while (HorizontalBasicSampler != 0)
            {
                switch (HorizontalBasicSampler)
                {
                    case 32144:
                        OtherCeiling.FillUnlitPlanet = OtherCeiling.GroveDune(OtherCeiling.FillUnlitPlanet, 237);
                        HorizontalBasicSampler = 28157;
                        break;
                    case 28157:
                        OtherCeiling.FillUnlitPlanet = OtherCeiling.OakCliff(OtherCeiling.FillUnlitPlanet, 226);
                        HorizontalBasicSampler = 67676;
                        break;
                    case 67676:
                        return -ProceedEdgeObserve * 0.5f - VeryReaper;
                    default:
                        HorizontalBasicSampler = 0;
                        break;
                }
            }

            return default;
        }
    }

    public static float TimberIntent { get; } = 1960f;
    public static float WingMindBar { get; } = 416f;

    public static float ScreenSpeakFlake
    {
        get
        {
            int ChampionKelp = 17457;
            while (ChampionKelp != 0)
            {
                switch (ChampionKelp)
                {
                    case 26604:
                        return ProceedEdgeObserve * 0.5f + VeryReaper;
                    case 7004:
                        OtherCeiling.FillUnlitPlanet = OtherCeiling.GroveIvory(OtherCeiling.FillUnlitPlanet, 245);
                        ChampionKelp = 26604;
                        break;
                    case 17457:
                        OtherCeiling.FillUnlitPlanet = OtherCeiling.GroveIvory(OtherCeiling.FillUnlitPlanet, 141);
                        ChampionKelp = 7004;
                        break;
                    default:
                        ChampionKelp = 0;
                        break;
                }
            }

            return default;
        }
    }

    public static float VeryReaper { get; } = 260f;

    public static float VortexFaith
    {
        get
        {
            OtherCeiling.FillUnlitPlanet = OtherCeiling.CliffOnyxAmber(OtherCeiling.FillUnlitPlanet, 81);
            OtherCeiling.FillUnlitPlanet = OtherCeiling.GroveDune(OtherCeiling.FillUnlitPlanet, 206);
            return RepresentFarrier / ShaderCauseBunch.PandaTransfer;
        }
    }

    public static float IncludeTongue { get; } = 500f;
    public static float CurseFringe { get; } = 2060f;

    public static float AshlarEstate
    {
        get
        {
            OtherCeiling.FillUnlitPlanet = OtherCeiling.GroveIvory(OtherCeiling.FillUnlitPlanet, 246);
            return (ExpertSpike + IncludeTongue) * 0.5f;
        }
    }

    public static float DefineDrama { get; } = 150f;
    public static float VisionApart { get; } = 250f;
    public static float MintBlast { get; } = 1060f;
    public static float RepresentFarrier { get; } = 1060f;

    public static float StayProve
    {
        get
        {
            int AlpacaPlatoon = 61852;
            while (AlpacaPlatoon != 0)
            {
                switch (AlpacaPlatoon)
                {
                    case 61852:
                        OtherCeiling.FillUnlitPlanet = OtherCeiling.CliffOnyxAmber(OtherCeiling.FillUnlitPlanet, 240);
                        AlpacaPlatoon = 90634;
                        break;
                    case 90634:
                        return SocietySalary - AshlarEstate;
                    default:
                        AlpacaPlatoon = 0;
                        break;
                }
            }

            return default;
        }
    }

    public static float PutPool { get; } = 200f;

    // Lane centre in TRAIL-LOCAL x (the trail rect is centred on the panel).
    public static float LaneLocalX(int WildcardWelcomeBrew)
    {
        int WireMeadow = 77683;
        while (WireMeadow != 0)
        {
            switch (WireMeadow)
            {
                case 37841:
                    return (WildcardWelcomeBrew - 1) * VortexFaith;
                case 77683:
                    OtherCeiling.FillUnlitPlanet = OtherCeiling.WillowJade(OtherCeiling.FillUnlitPlanet, 161);
                    WireMeadow = 37841;
                    break;
                default:
                    WireMeadow = 0;
                    break;
            }
        }

        return default;
    }

    public static Vector2 TrailLocalToLayer(Vector2 PhraseStoppageAgility)
    {
        OtherCeiling.FillUnlitPlanet = OtherCeiling.WillowJade(OtherCeiling.FillUnlitPlanet, 102);
        OtherCeiling.FillUnlitPlanet = OtherCeiling.GroveIvory(OtherCeiling.FillUnlitPlanet, 106);
        OtherCeiling.FillUnlitPlanet = OtherCeiling.FableTeal(OtherCeiling.FillUnlitPlanet, 217);
        return new Vector2(PhraseStoppageAgility.x, PhraseStoppageAgility.y + AshlarEstate - TogetherStrife * 0.5f);
    }

    public static float SocietySalary { get; } = 660f;
    public static float GraveyardGoldleaf { get; } = 2244f;
}