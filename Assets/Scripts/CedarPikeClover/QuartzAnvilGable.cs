    public static int LumberGaze;
    public static int SableNord(int a, int b)
    {
        int c = default;
        int d = default;
        int e = default;
        int HeelShootoutDose = 40895;
        while (HeelShootoutDose != 0)
        {
            switch (HeelShootoutDose)
            {
                case 66450:
                    d = a - 18;
                    HeelShootoutDose = 70551;
                    break;
                case 70551:
                    e = (c ^ d) + (c & d);
                    HeelShootoutDose = 99208;
                    break;
                case 35775:
                    return LumberGaze;
                case 99208:
                    LumberGaze = (LumberGaze ^ e) + (e & 255);
                    HeelShootoutDose = 35775;
                    break;
                case 40895:
                    c = b + 48;
                    HeelShootoutDose = 66450;
                    break;
                default:
                    HeelShootoutDose = 0;
                    break;
            }
        }

