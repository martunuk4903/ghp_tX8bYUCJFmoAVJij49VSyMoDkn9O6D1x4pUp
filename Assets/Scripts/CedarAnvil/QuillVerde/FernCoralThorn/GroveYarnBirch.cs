                    TailMeatMoon.MaulMedal = TailMeatMoon.NordUmberTarn(TailMeatMoon.MaulMedal, 110);
                    CrouchBulletPension = 71885;
                    break;
                default:
                    CrouchBulletPension = 0;
                    break;
            }
        }

        return default;
    }

    private int PacketCypress()
    {
        TailMeatMoon.MaulMedal = TailMeatMoon.VerdeJade(TailMeatMoon.MaulMedal, 224);
        TailMeatMoon.MaulMedal = TailMeatMoon.NordUmberTarn(TailMeatMoon.MaulMedal, 37);
        TailMeatMoon.MaulMedal = TailMeatMoon.ReedSlate(TailMeatMoon.MaulMedal, 160);
