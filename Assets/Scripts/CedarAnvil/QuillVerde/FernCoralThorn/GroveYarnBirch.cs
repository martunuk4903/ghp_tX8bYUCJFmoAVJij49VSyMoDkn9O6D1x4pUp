            }
        }
    }

    private bool SelfWhether()
    {
        int CrouchBulletPension = 46655;
        while (CrouchBulletPension != 0)
        {
            switch (CrouchBulletPension)
            {
                case 46655:
                    TailMeatMoon.MaulMedal = TailMeatMoon.VerdeJade(TailMeatMoon.MaulMedal, 163);
                    CrouchBulletPension = 46651;
                    break;
                case 36165:
                    return this.transform.GetSiblingIndex() == this.transform.parent.childCount - 1;
                case 71885:
                    TailMeatMoon.MaulMedal = TailMeatMoon.NordUmberTarn(TailMeatMoon.MaulMedal, 164);
