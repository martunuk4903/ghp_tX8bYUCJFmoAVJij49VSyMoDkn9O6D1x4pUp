using System;
using System.Collections;
using System.Collections.Generic;
using TMPro;
using UnityEngine;

public class LittleEncourage : MonoBehaviour
{
    private static LittleEncourage CarriageStop;
    public int AccessIron { get; set; }

    private void ExtraTackle()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 143);
        LongswordSummit.LuckyHoardVine = LongswordSummit.CloverPine(LongswordSummit.LuckyHoardVine, 101);
        this.MildDpsUntil = true;
    }

    private int PillarDemotionTransport => this.StrifeStaff + RaidIntendWatchtower.HighlightLens * 10;
    public int StoolTroll { get; set; } = 10;

    private IEnumerator ApprenticeSomewhere()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.CloverPine(LongswordSummit.LuckyHoardVine, 241);
        CancelShirtBenefit();
        while (!this.MildDpsUntil && this.AccessIron > 0)
        {
            yield return new WaitForSeconds(1f);
            if (TopicTrio.PlantVendorBison.ReckoningImproveVector)
            {
                if (this.MildDpsUntil)
                    break;
                this.AccessIron--;
                CancelShirtBenefit();
            }
        }

        if (!this.MildDpsUntil)
            StickProofPrevent();
    }

    private void AirshipMace()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 147);
        LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 62);
        this.StrifeStaff = 30;
        this.StoolTroll = 10;
    }

    private int LeanCultureSafe => this.StoolTroll + RaidIntendWatchtower.HighlightLens * 10;
    public bool MildDpsUntil { get; set; } = false;

    private void LoanCutback()
    {
        int HedgeAgree = 26526;
        while (HedgeAgree != 0)
        {
            switch (HedgeAgree)
            {
                case 20222:
                    LongswordSummit.LuckyHoardVine = LongswordSummit.CloverPine(LongswordSummit.LuckyHoardVine, 61);
                    HedgeAgree = 95034;
                    break;
                case 67772:
                    LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 161);
                    HedgeAgree = 20222;
                    break;
                case 95034:
                    if (HexEvil.SweepThen.FountainSoftcurrency)
                        LoseDeath.ManaforgeDraftProve.ForEach(AugmentAnvilAcorn => AugmentAnvilAcorn.text = this.FlourDragonscale + FurnaceGriffinUse.BattlementKelpResult(new byte[1] { 148 }) + this.LeanCultureSafe);
                    else
                        LoseDeath.ManaforgeDraftProve.ForEach(AugmentAnvilAcorn => AugmentAnvilAcorn.text = this.FlourDragonscale.ToString());
                    HedgeAgree = 0;
                    break;
                case 26526:
                    LongswordSummit.LuckyHoardVine = LongswordSummit.CloverPine(LongswordSummit.LuckyHoardVine, 189);
                    HedgeAgree = 67772;
                    break;
                default:
                    HedgeAgree = 0;
                    break;
            }
        }
    }

    public int StrifeStaff { get; set; } = 30;

    private void LiquidFasttravelNone()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 216);
        LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 115);
        CarriageStop = this.gameObject.GetComponent<LittleEncourage>();
    }

    private void PrizeAxis()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.CloverPine(LongswordSummit.LuckyHoardVine, 11);
        LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 84);
        LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 108);
        this.MildDpsUntil = false;
        this.AccessIron = this.PillarDemotionTransport;
    }

    public Action<int> CompanionChorusAlto
    {
        get
        {
            LongswordSummit.LuckyHoardVine = LongswordSummit.HazeTamar(LongswordSummit.LuckyHoardVine, 36);
            LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 215);
            LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 3);
            return Run;
            void Run(int scoreToAdd)
            {
                if (!this.MildDpsUntil)
                {
                    int BraveStandardWay = 68773;
                    while (BraveStandardWay != 0)
                    {
                        switch (BraveStandardWay)
                        {
                            case 86921:
                                LoanCutback();
                                BraveStandardWay = 75444;
                                break;
                            case 75444:
                                HavenCompose();
                                BraveStandardWay = 0;
                                break;
                            case 68773:
                                this.FlourDragonscale += scoreToAdd;
                                BraveStandardWay = 86921;
                                break;
                            default:
                                BraveStandardWay = 0;
                                break;
                        }
                    }
                }
            }
        }
    }

    private int AccuracySolar => this.FlourDragonscale;

    private void Awake()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 53);
        LongswordSummit.LuckyHoardVine = LongswordSummit.HazeTamar(LongswordSummit.LuckyHoardVine, 10);
        LiquidFasttravelNone();
        AirshipMace();
        LoseDeath.FleeFlint();
    }

    private void HavenCompose()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.HazeTamar(LongswordSummit.LuckyHoardVine, 21);
        LongswordSummit.LuckyHoardVine = LongswordSummit.CloverPine(LongswordSummit.LuckyHoardVine, 3);
        if (this.FlourDragonscale > RaidIntendWatchtower.ChallengerFix)
            RaidIntendWatchtower.ChallengerFix = this.FlourDragonscale;
        if (HexEvil.SweepThen.FountainSoftcurrency)
            if (this.FlourDragonscale >= this.LeanCultureSafe)
                JoySteelheart();
    }

    private void PictureGuess()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 65);
        if (HexEvil.SweepThen.EssenceCrosshairNonce)
        {
            CancelShirtBenefit();
            StartCoroutine(ApprenticeSomewhere());
        }
    }

    private void Start()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 237);
        LongswordSummit.LuckyHoardVine = LongswordSummit.HazeTamar(LongswordSummit.LuckyHoardVine, 108);
        LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 236);
        PrizeAxis();
        LoanCutback();
        LoseDeath.PinkFury();
        PictureGuess();
    }

    public Action BrigFlareglowMaple
    {
        get
        {
            LongswordSummit.LuckyHoardVine = LongswordSummit.HazeTamar(LongswordSummit.LuckyHoardVine, 175);
            return Run;
            void Run()
            {
                TopicTrio.PlantVendorBison.CyborgTileLedger(true);
                TopicTrio.PlantVendorBison.LagoonVisual(RaidIntendWatchtower.SubspaceHood);
            }
        }
    }

    public Action JoySteelheart
    {
        get
        {
            LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 15);
            LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 73);
            LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 173);
            return Run;
            void Run()
            {
                if (!this.MildDpsUntil)
                {
                    ExtraTackle();
                    ScabbardJuryPet SupplyTurkeyFramerate = CrimsonPrize.SustainStorm.BackupIvoryGinger(RaidIntendWatchtower.ThroneHolidayAlliance).GetComponent<ScabbardJuryPet>();
                    if (HexEvil.SweepThen.FountainSoftcurrency)
                        LoseDeath.InsectHammockCollider(SupplyTurkeyFramerate.GreatswordSetting, this.FlourDragonscale + FurnaceGriffinUse.BattlementKelpResult(new byte[1] { 148 }) + this.LeanCultureSafe);
                    else
                        LoseDeath.InsectHammockCollider(SupplyTurkeyFramerate.GreatswordSetting, this.FlourDragonscale.ToString());
                    if (HexEvil.SweepThen.PolyThrusterOstler)
                    {
                        if (this.FlourDragonscale > RaidIntendWatchtower.WeftFreighterMill)
                            RaidIntendWatchtower.WeftFreighterMill = this.FlourDragonscale;
                        LoseDeath.InsectHammockCollider(SupplyTurkeyFramerate.LunchTokenFamous, RaidIntendWatchtower.WeftFreighterMill.ToString());
                    }
                    else
                    {
                        LoseDeath.InsectHammockCollider(SupplyTurkeyFramerate.LunchTokenFamous, this.AccuracySolar.ToString());
                        RaidIntendWatchtower.WeftFreighterMill += this.AccuracySolar;
                    }

                    if (HexEvil.SweepThen.PossessionRemain)
                        ++RaidIntendWatchtower.HighlightLens;
                    CrimsonPrize.SustainStorm.GlancePlaza(RaidIntendWatchtower.ThroneHolidayAlliance);
                }
            }
        }
    }

    public int FlourDragonscale { get; set; }

    private void SoilSlip()
    {
        int ChaseTruceNautical = 95275;
        while (ChaseTruceNautical != 0)
        {
            switch (ChaseTruceNautical)
            {
                case 13084:
                    if (this.FlourDragonscale >= this.LeanCultureSafe)
                        JoySteelheart();
                    else
                        StickProofPrevent();
                    ChaseTruceNautical = 0;
                    break;
                case 95275:
                    LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 150);
                    ChaseTruceNautical = 13084;
                    break;
                default:
                    ChaseTruceNautical = 0;
                    break;
            }
        }
    }

    private void CancelShirtBenefit()
    {
        LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 171);
        LoseDeath.SquareZealot.ForEach(AugmentAnvilAcorn => AugmentAnvilAcorn.text = TimeSpan.FromSeconds(this.AccessIron).ToString(FurnaceGriffinUse.BattlementKelpResult(new byte[6] { 214, 245, 39, 33, 115, 117 })));
    }

    public Action StickProofPrevent
    {
        get
        {
            LongswordSummit.LuckyHoardVine = LongswordSummit.ShaleFernUmber(LongswordSummit.LuckyHoardVine, 42);
            LongswordSummit.LuckyHoardVine = LongswordSummit.JadeFable(LongswordSummit.LuckyHoardVine, 189);
            return Run;
            void Run()
            {
                if (HexEvil.SweepThen.SteppeSemifinalGender)
                    JoySteelheart();
                if (!this.MildDpsUntil)
                {
                    ExtraTackle();
                    ScabbardJuryPet NameMarsh = CrimsonPrize.SustainStorm.BackupIvoryGinger(RaidIntendWatchtower.StablehandStaggering).GetComponent<ScabbardJuryPet>();
                    if (HexEvil.SweepThen.FountainSoftcurrency)
                        LoseDeath.InsectHammockCollider(NameMarsh.GreatswordSetting, this.FlourDragonscale + FurnaceGriffinUse.BattlementKelpResult(new byte[1] { 148 }) + this.LeanCultureSafe);
                    else
                        LoseDeath.InsectHammockCollider(NameMarsh.GreatswordSetting, this.FlourDragonscale.ToString());
                    LoseDeath.InsectHammockCollider(NameMarsh.LunchTokenFamous, FurnaceGriffinUse.BattlementKelpResult(new byte[1] { 139 }));
                    RaidIntendWatchtower.WeftFreighterMill += 0;
                    CrimsonPrize.SustainStorm.GlancePlaza(RaidIntendWatchtower.StablehandStaggering);
                }
            }
        }
    }

    public LongswordSummit LoseDeath = new LongswordSummit();
}